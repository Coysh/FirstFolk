/** Screenshots of bridge mode (ghost) and a finished bridge. Needs the dev server. node tools/bridge-shot.mjs [--seed 2] [--night 0] */
import { chromium } from 'playwright';
const args = process.argv.slice(2);
const opt = (n, d) => { const i = args.indexOf(`--${n}`); return i >= 0 ? args[i + 1] : d; };
const seed = Number(opt('seed', '2'));
const night = Number(opt('night', '0'));
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await (await browser.newContext({ viewport: { width: 1440, height: 880 }, deviceScaleFactor: 1 })).newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
await page.goto('http://localhost:5173');
await page.waitForFunction(() => window.firstfolk?.shell, null, { timeout: 30000 });
await page.evaluate((s) => window.firstfolk.shell.newGame(s, 'normal'), seed);
await page.waitForFunction(() => window.firstfolk.shell.screen.value === 'game', null, { timeout: 60000 });
const info = await page.evaluate(async () => {
  const { bestBridge } = await import('/src/sim/bridges.ts');
  const { claimArea } = await import('/src/sim/territory.ts');
  const game = window.firstfolk.shell.game;
  const w = game.world;
  const p = w.players[0];
  p.rank = 1;
  const wagon = [...w.buildings.values()].find((b) => b.type === 'wagon');
  wagon.stock.logs = 200; wagon.stock.stone = 100;
  const c = Math.floor(w.size / 2);
  claimArea(w, 0, c, c, 26);
  w.explored.fill(3);
  const pick = bestBridge(w, 0);
  if (pick) game.startBridging(pick.span);
  game.view.rig.goalDistance = 14;
  for (const b of document.querySelectorAll('button')) if (b.textContent.trim() === 'Later') b.click();
  return { valley: w.map.valley, pick: pick && { ...pick.span, score: pick.score } };
});
console.log(JSON.stringify(info));
await page.waitForTimeout(3500);
await page.screenshot({ path: 'screenshots/bridge-ghost.png' });
if (night) await page.evaluate((n) => { const v = window.firstfolk.shell.game.view; v.time = 110; v.dayAmt = 1 - n; }, night);
await page.evaluate(() => window.firstfolk.shell.game.confirmBridge());
await page.evaluate(() => { const g = window.firstfolk.shell.game; for (let i = 0; i < 400; i++) { g.world.step(); } g.view.handleEvents(g.world.drainEvents()); });
await page.waitForTimeout(3500);
await page.screenshot({ path: `screenshots/bridge-built${night ? '-night' : ''}.png` });
if (errors.length) console.log('ERRORS:', [...new Set(errors)].join('\n'));
await browser.close();
